// Bundles the USWDS custom elements (src/js) with the official USWDS behavior
// modules they wrap into one browser script for OutSystems:
//   dist/js/uswds-os.js       readable, for review and debugging
//   dist/js/uswds-os.min.js   → USWDS_Patterns Script resource, required by the Web Component Blocks

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const version = JSON.parse(fs.readFileSync(path.join(root, "node_modules/@uswds/uswds/package.json"), "utf8")).version;
const banner = `/*! uswds-os custom elements | USWDS ${version} | generated by scripts/build-js.mjs, do not edit */`;

for (const minify of [false, true]) {
  const outfile = path.join(root, `dist/js/uswds-os${minify ? ".min" : ""}.js`);
  await build({
    entryPoints: [path.join(root, "src/js/index.js")],
    bundle: true,
    format: "iife",
    target: "es2020",
    minify,
    legalComments: "none",
    banner: { js: banner },
    outfile,
    logLevel: "warning",
  });
  const kb = (fs.statSync(outfile).size / 1024).toFixed(1);
  console.log(`${path.relative(root, outfile)}  ${kb} KB`);
}
